const (
	validationOpenAPISchema = `{"openapi":"3.1.0","info":{"title":"Example","version":"1"},"servers":[{"url":"https://8.8.8.8"}],"paths":{}}`
)

func TestValidateOpenAPISources(t *testing.T) {
	var requests atomic.Int32
	source := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		requests.Add(1)
		assert.Empty(t, r.Header.Get("Authorization"))
		assert.Empty(t, r.Header.Get("Cookie"))
		_, _ = w.Write([]byte(validationOpenAPISchema))
	}))
	defer source.Close()
	tests := []struct {
		name         string
		source       types.OpenAPISource
		schema       *types.OpenAPISchema
		allowLocal   bool
		wantError    string
		wantRequests int
	}{
		{
			name:   "inline source",
			source: types.OpenAPISource{Content: validationOpenAPISchema},
		},
		{
			name:         "URL source under configured policy",
			source:       types.OpenAPISource{URL: source.URL},
			allowLocal:   true,
			wantRequests: 1,
		},
		{
			name:      "blocked loopback source",
			source:    types.OpenAPISource{URL: source.URL},
			wantError: "schema source URL is blocked",
		},
		{
			name:       "caller supplied snapshot",
			source:     types.OpenAPISource{URL: source.URL},
			schema:     &types.OpenAPISchema{Raw: json.RawMessage(validationOpenAPISchema)},
			allowLocal: true,
			wantError:  "schema is generated by Obot",
		},
		{
			name:      "malformed source",
			source:    types.OpenAPISource{Content: "not an OpenAPI document"},
			wantError: "failed to import OpenAPI schema",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			before := requests.Load()
			entry := types.MCPServerCatalogEntryManifest{
				Name:     "Example API",
				EntryKey: "example",
				Runtime:  types.RuntimeOpenAPI,
				OpenAPIConfig: &types.OpenAPIRuntimeConfig{
					Source: tt.source,
					Schema: tt.schema,
				},
			}
			data, err := json.Marshal(entry)
			require.NoError(t, err)
			validator := newTestValidator()
			validator.mcpOptions.DevMode = true // Local HTTP schema source in this test only.
			validator.mcpOptions.RemoteMCPURLValidationConfig.AllowLocalhostMCP = tt.allowLocal
			diagnostics, err := validator.validate(t.Context(), []CatalogFile{{Path: "api.json", Content: string(data)}})
			require.NoError(t, err)
			require.Equal(t, tt.wantRequests, int(requests.Load()-before))
			if tt.wantError != "" {
				require.Positive(t, errorCount(diagnostics))
				require.Contains(t, diagnostics[0].Message, tt.wantError)
				return
			}
			require.Zero(t, errorCount(diagnostics), "%+v", diagnostics)
			prepared := validator.entries[mcpcatalog.SourceRef(mcp.SourceIDForURL(testSourceURL), "example")]
			require.JSONEq(t, validationOpenAPISchema, string(prepared.OpenAPIConfig.Schema.Raw))
		})
	}
}

func TestValidateRetainedConfiguration(t *testing.T) {
	content := strings.Replace(validVMCP, "        secretBinding:\n          name: github\n          key: token", "", 1)
	tests := []struct {
		name       string
		previous   map[string]string
		wantErrors int
	}{
		{
			name:       "new vMCP requires a value",
			wantErrors: 1,
		},
		{
			name:     "retained value supplies the same component",
			previous: map[string]string{vmcpconfig.ConfigurationKey("github", "TOKEN"): "not-returned"},
		},
		{
			name:       "different component does not supply the value",
			previous:   map[string]string{vmcpconfig.ConfigurationKey("old-github", "TOKEN"): "not-returned"},
			wantErrors: 1,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			validator := newTestValidator()
			validator.existingConfiguration = func(_ context.Context, key, name string) (map[string]string, error) {
				require.Equal(t, "support", key)
				require.Equal(t, "Support", name)
				return tt.previous, nil
			}
			diagnostics, err := validator.validate(t.Context(), []CatalogFile{{Path: "support.yaml", Content: content}})
			require.NoError(t, err)
			require.Equal(t, tt.wantErrors, errorCount(diagnostics), "%+v", diagnostics)
			data, err := json.Marshal(diagnostics)
			require.NoError(t, err)
			require.NotContains(t, string(data), "not-returned")
		})
	}
}

func TestSensitiveEntryValuesAreWarnings(t *testing.T) {
	content := `name: Example
entryKey: example
runtime: npx
npxConfig:
  package: example
config:
  - key: TOKEN
    usage: env
    sensitive: true
    value: do-not-echo-this-value
`
	diagnostics, err := newTestValidator().validate(t.Context(), []CatalogFile{{Path: "entry.yaml", Content: content}})
	require.NoError(t, err)
	require.Zero(t, errorCount(diagnostics))
	require.Len(t, diagnostics, 1)
	require.Equal(t, severityWarning, diagnostics[0].Severity)
	require.Contains(t, diagnostics[0].Message, "Kubernetes secretBinding")
	require.NotContains(t, diagnostics[0].Message, "do-not-echo-this-value")
}

func TestWildcardGrantWithoutStoredToolList(t *testing.T) {
	content := strings.Replace(validVMCP, "allowedTools: []", "allowedTools: ['*']", 1)
	validator := newTestValidator()
	diagnostics, err := validator.validate(t.Context(), []CatalogFile{{Path: "support.yaml", Content: content}})
	require.NoError(t, err)
	require.Zero(t, errorCount(diagnostics), "%+v", diagnostics)
	access := validator.access[0].Profiles[0].Components[1]
	require.Equal(t, "slack", access.Component)
	require.True(t, access.AllTools)
	require.True(t, access.Unknown)
	require.Nil(t, access.Tools)
	require.Len(t, diagnostics, 1)
	require.Contains(t, diagnostics[0].Message, "including tools enabled on it later")
}

func TestRetainedConfigurationLookupFailureIsNotSuccessfulValidation(t *testing.T) {
	validator := newTestValidator()
	validator.existingConfiguration = func(context.Context, string, string) (map[string]string, error) {
		return nil, fmt.Errorf("credential store unavailable")
	}
	content := strings.Replace(validVMCP, "        secretBinding:\n          name: github\n          key: token", "", 1)
	_, err := validator.validate(t.Context(), []CatalogFile{{Path: "support.yaml", Content: content}})
	require.ErrorContains(t, err, "failed to check retained vMCP configuration")
}
